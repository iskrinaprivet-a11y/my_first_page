/**
 * Максимальная сторона картинки на холсте, в координатах канваса.
 *
 * Ограничение обязательно: фотография с телефона — 4000×3000, и в таком виде
 * она закрыла бы весь холст целиком. Всё, что длиннее этой стороны,
 * уменьшается пропорционально; мелкие картинки не увеличиваются.
 */
export const MAX_IMAGE_EDGE_PX = 640

/**
 * Префикс типа файла, по которому файл считается картинкой.
 *
 * Проверка по типу, а не по расширению имени: буфер обмена отдаёт файлы без
 * расширений, а «.png» в имени не делает файл изображением.
 */
export const IMAGE_MIME_PREFIX = 'image/'

/**
 * Тип элемента буфера, который содержит файл, — так отдаёт снимок экрана
 * (Chrome, Firefox). Второй источник картинок в буфере — элементы типа 'file'.
 */
export const CLIPBOARD_FILE_KIND = 'file'

/**
 * Тип в dataTransfer, который браузер ставит для перетаскивания файлов из
 * проводника. По нему холст понимает, что нести ему будут файл, а не строку.
 */
export const DATA_TRANSFER_FILES = 'Files'

/** Подсказка про вставку картинок в нижней панели холста. */
export const INSERT_IMAGE_HINT = 'Ctrl+V — картинка из буфера · файл можно перетащить'