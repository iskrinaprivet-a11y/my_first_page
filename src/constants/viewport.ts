/**
 * КОНСТАНТЫ КАМЕРЫ И СЕТКИ.
 *
 * Границы зума и шаг сетки — тоже настройки, а не магические числа в коде:
 * меняем здесь, и все хуки/компоненты подхватят новое значение.
 */

import type { ShapeType, Viewport } from '../types/shape'

/** Минимальный зум — 10%. */
export const MIN_ZOOM = 0.1
/** Максимальный зум — 400%. */
export const MAX_ZOOM = 4
/** Зум при запуске и по кнопке сброса. */
export const INITIAL_ZOOM = 1

/** Множитель зума за один «зум-шаг» (кнопки, ctrl+колесо). */
export const ZOOM_STEP = 1.2

/**
 * Чувствительность колеса. Значение делит deltaY (обычно ±100 за щелчок),
 * поэтому экспонента даёт плавный, но управляемый зум.
 */
export const WHEEL_ZOOM_SENSITIVITY = 0.002
/** Пинч-жест браузер шлёт с ctrlKey=true — там отклик делаем мельче. */
export const PINCH_ZOOM_SENSITIVITY = 0.01

/** Шаг сетки в координатах канваса. */
export const GRID_SIZE = 20
/** Сетка рисуется с шагом GRID_SIZE; крупная — в 5 раз реже. */
export const GRID_MAJOR_EVERY = 5

/** Камера по умолчанию: канвас в точке (0, 0), без сдвига. */
export const DEFAULT_VIEWPORT: Viewport = { zoom: INITIAL_ZOOM, panX: 0, panY: 0 }

/** Подпись вида фигуры: 'rectangle' → 'Прямоугольник'. */
export const SHAPE_LABELS: Readonly<Record<ShapeType, string>> = {
  rectangle: 'Прямоугольник',
  ellipse: 'Эллипс',
  image: 'Изображение',
}

/** Заливка и обводка по умолчанию для новых фигур. */
export const DEFAULT_FILL = '#3b82f6'
export const DEFAULT_STROKE = '#1d4ed8'
export const DEFAULT_STROKE_WIDTH = 1

/**
 * Минимальная длина протяжки в ЭКРАННЫХ пикселях, при которой ещё создаётся
 * фигура.
 *
 * Именно экранных, а не координат канваса: на зуме 10% один и тот же жест мыши
 * даёт разный размер в единицах канваса, и порог «4 единицы» превращался бы то
 * в невидимую фигуру, то в случайную. Экранная величина отражать намерение
 * пользователя не зависимо от зума.
 */
export const MIN_DRAG_SCREEN_PX = 4

/**
 * Сколько изменений помнит история документа (Ctrl+Z).
 *
 * Ограничение обязательно: без него стек снимков рос бы бесконечно и держал
 * в памяти десятки копий всех фигур на каждом шаге.
 */
export const HISTORY_LIMIT = 50
